"""专家与专家团重构的统一错误码。"""

from enum import StrEnum
from typing import Any


class ExpertErrorCode(StrEnum):
    LEGACY_SUITE_UNSUPPORTED = "LEGACY_SUITE_UNSUPPORTED"
    BUILTIN_EXPERT_NOT_LISTED = "BUILTIN_EXPERT_NOT_LISTED"
    EXPERT_UNAVAILABLE = "EXPERT_UNAVAILABLE"
    EXPERT_NOT_FOUND = "EXPERT_NOT_FOUND"
    EXPERT_ID_AMBIGUOUS = "EXPERT_ID_AMBIGUOUS"
    EXPERT_TOOL_SURFACE_EMPTY = "EXPERT_TOOL_SURFACE_EMPTY"
    EXPERT_PROMPT_TOO_LONG = "EXPERT_PROMPT_TOO_LONG"
    SKILL_SELECTION_LIMIT = "SKILL_SELECTION_LIMIT"
    SKILL_TOOL_UNRESOLVED = "SKILL_TOOL_UNRESOLVED"
    TEAM_REGISTRY_UNAVAILABLE = "TEAM_REGISTRY_UNAVAILABLE"
    # 预留：付费权益门禁本期为空实现并放行，见 01 §12
    EXPERT_FORBIDDEN = "EXPERT_FORBIDDEN"
    MANIFEST_AGENT_TOOLS_FORBIDDEN = "MANIFEST_AGENT_TOOLS_FORBIDDEN"
    MANIFEST_AGENT_TOO_LONG = "MANIFEST_AGENT_TOO_LONG"
    MANIFEST_INVALID = "MANIFEST_INVALID"
    MANIFEST_EXPERT_DEPENDS_ON_EXPERT = "MANIFEST_EXPERT_DEPENDS_ON_EXPERT"
    MANIFEST_EXPERT_HAS_HOOKS_OR_MCP = "MANIFEST_EXPERT_HAS_HOOKS_OR_MCP"
    # 预留：清单热部署重建失败时保留旧 registry；本期清单仅启动加载一次
    BUILTIN_REGISTRY_LOAD_FAILED = "BUILTIN_REGISTRY_LOAD_FAILED"
    MODULE_DISABLED = "MODULE_DISABLED"
    STATE_UNKNOWN_MODULE = "STATE_UNKNOWN_MODULE"
    STATE_KIND_MISMATCH = "STATE_KIND_MISMATCH"
    CAPABILITY_POLICY_LOAD_FAILED = "CAPABILITY_POLICY_LOAD_FAILED"


class ExpertError(Exception):
    def __init__(
        self,
        code: ExpertErrorCode,
        message: str,
        detail: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.detail = detail


__all__ = ["ExpertError", "ExpertErrorCode"]
