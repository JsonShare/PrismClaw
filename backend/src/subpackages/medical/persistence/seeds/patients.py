async def seed_patients_data(engine: AsyncEngine) -> None:
    """幂等灌入患者与报告种子数据。"""
    from ..medical_store import MedicalStore

    store = MedicalStore(engine)

    for p in _PATIENT_SEEDS:
        pid = p.pop("id")
        await store.upsert_patient(pid, p)
        # 还原 id 供重跑
        p["id"] = pid
    logger.info("患者种子灌入完成: %d 条", len(_PATIENT_SEEDS))

    for r in _REPORT_SEEDS:
        # asyncpg 严格类型：DATE/TIMESTAMP 列不接受 str，必须转 native 对象
        if "visit_date" in r and isinstance(r["visit_date"], str):
            r["visit_date"] = date.fromisoformat(r["visit_date"])
        rid = r.pop("id")
        pid = r.pop("patient_id")
        # 检查是否已存在（幂等）
        existing = await store.get_report(rid)
        if not existing:
            await store.create_report(rid, pid, r)
        # 还原供重跑
        r["id"] = rid
        r["patient_id"] = pid
    logger.info("报告种子灌入完成: %d 条", len(_REPORT_SEEDS))
